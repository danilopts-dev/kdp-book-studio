// Cabelo cacheado: cachos redondos fundidos numa massa; arcos internos marcam os cachos.
function hairCurly(f, L) {
  const ring = [];
  const n = 9;
  for (let i = 0; i < n; i++) {
    const a = ((-28 - (i / (n - 1)) * 196) * Math.PI) / 180;
    ring.push([Math.cos(a) * 10.2, -0.6 + Math.sin(a) * 10.4]);
  }
  ring.forEach(([x, y]) => f.ell(L, x, y, 3.5, 3.3));
  f.shape(L, [[-8.6, 4.6, 1], [-9.4, -3], [-6, -8.6], [0, -10.6], [6.4, -8.6], [9.2, -5.2], [7.6, -6.2], [4.8, -5.6], [2, -6.6],
    [-1, -5.4], [-4.4, -5.8], [-6.6, -3.2], [-7.6, 0.8]]);
  for (let i = 1; i < n - 1; i++) {
    const [x, y] = ring[i];
    const a0 = Math.atan2(y + 0.6, x);
    const pts = [];
    for (let k = 0; k <= 4; k++) {
      const t = a0 + Math.PI * 0.55 + (k / 4) * Math.PI * 0.75;
      pts.push([x + Math.cos(t) * 2.2, y + Math.sin(t) * 2.1]);
    }
    if (i % 2 === 0) f.line(L, pts);
  }
}

